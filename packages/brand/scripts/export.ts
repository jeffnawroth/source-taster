// Manual, maintainer-run export: `pnpm --filter @source-taster/brand brand:export`.
// Writes the SVG masters, their gamut record, the raster/ICO exports and the
// hashed export manifest. Product builds and tests only read the committed
// results; nothing here runs during a build, typecheck or test.
import { chromium } from "@playwright/test";
import { createHash } from "node:crypto";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { exportJobs } from "../src/exports.ts";
import { brandMasters, gamutRecord } from "../src/masters.ts";
import { webManifest } from "../src/web-head.ts";

const root = new URL("../", import.meta.url);
const mastersDir = new URL("masters/", root);
const exportsDir = new URL("exports/", root);
const sha256 = (bytes: string | Buffer) =>
  createHash("sha256").update(bytes).digest("hex");

const masters = brandMasters();
for (const dir of [mastersDir, exportsDir]) {
  await rm(dir, { recursive: true, force: true });
  await mkdir(dir, { recursive: true });
}
for (const [name, svg] of Object.entries(masters))
  await writeFile(new URL(name, mastersDir), svg);
await writeFile(
  new URL("gamut-mapping.json", mastersDir),
  `${JSON.stringify(gamutRecord(), null, 2)}\n`,
);

// Chromium's canvas renders each master as vector art at the target size.
const browser = await chromium.launch();
const page = await browser.newPage();
const written = new Map<string, Buffer>();
try {
  for (const job of exportJobs) {
    if (job.entries) continue;
    if (job.generated === "web-manifest") {
      written.set(
        job.file,
        Buffer.from(`${JSON.stringify(webManifest(), null, 2)}\n`),
      );
      continue;
    }
    const master = masters[job.master!]!;
    if (!job.size) {
      written.set(job.file, Buffer.from(master));
      continue;
    }
    const base64 = await page.evaluate(
      async ({ svg, size }) => {
        const image = new Image();
        image.src = `data:image/svg+xml;base64,${btoa(svg)}`;
        await image.decode();
        const canvas = document.createElement("canvas");
        canvas.width = canvas.height = size;
        canvas.getContext("2d")!.drawImage(image, 0, 0, size, size);
        return canvas.toDataURL("image/png").split(",")[1]!;
      },
      {
        // Size the root element to the target so it rasterizes, not scales.
        svg: master.replace(
          /^<svg ([^>]*?)width="\d+" height="\d+"/,
          `<svg $1width="${job.size}" height="${job.size}"`,
        ),
        size: job.size,
      },
    );
    written.set(job.file, Buffer.from(base64, "base64"));
  }
} finally {
  await browser.close();
}

// A real ICO container whose entries are the exact PNG favicons.
for (const job of exportJobs.filter((job) => job.entries)) {
  const pngs = job.entries!.map((size) => written.get(`favicon-${size}.png`)!);
  const header = Buffer.alloc(6 + 16 * pngs.length);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(pngs.length, 4);
  let offset = header.length;
  job.entries!.forEach((size, index) => {
    const at = 6 + index * 16;
    header[at] = header[at + 1] = size;
    header.writeUInt16LE(1, at + 4);
    header.writeUInt16LE(32, at + 6);
    header.writeUInt32LE(pngs[index]!.length, at + 8);
    header.writeUInt32LE(offset, at + 12);
    offset += pngs[index]!.length;
  });
  written.set(job.file, Buffer.concat([header, ...pngs]));
}

for (const [file, bytes] of written)
  await writeFile(new URL(file, exportsDir), bytes);
const manifest = {
  note: "Generated by scripts/export.ts. Brand artwork: see ../NOTICE.md (draft, not legally reviewed).",
  masters: Object.fromEntries(
    Object.entries(masters).map(([name, svg]) => [name, sha256(svg)]),
  ),
  exports: exportJobs.map((job) => ({
    ...job,
    ...(job.master ? { masterSha256: sha256(masters[job.master]!) } : {}),
    sha256: sha256(written.get(job.file)!),
  })),
};
await writeFile(
  new URL("manifest.json", exportsDir),
  `${JSON.stringify(manifest, null, 2)}\n`,
);
// Fail closed if a file was rendered without being re-read identically.
for (const [file, bytes] of written)
  if (!bytes.equals(await readFile(new URL(file, exportsDir))))
    throw new Error(`Export ${file} did not round-trip`);
console.log(
  `Wrote ${Object.keys(masters).length} SVG masters and ${written.size} exports.`,
);

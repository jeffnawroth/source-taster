import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { format } from "prettier";
import { parse } from "culori";
import {
  backdrops,
  primitives,
  roles,
  shadows,
  values,
} from "../src/tokens.ts";
import type { Role, RoleValue } from "../src/tokens.ts";
import { color, css, hex, modes, over, resolve } from "./colors.ts";
import { assertContrast } from "./contrast.ts";

const palette = resolve();
const pairs = assertContrast(palette);
const names = Object.keys(palette.light) as Role[];
const colors = Object.fromEntries(
  modes.map((mode) => [
    mode,
    Object.fromEntries(
      names.map((name) => [
        name,
        {
          color: hex(palette[mode][name]),
          alpha: palette[mode][name].alpha ?? 1,
        },
      ]),
    ),
  ]),
);
const opaque = Object.fromEntries(
  Object.entries(backdrops).map(([name, value]) => {
    const bottom = parse(value);
    if (!bottom || bottom.mode !== "rgb")
      throw new Error("Invalid medium backdrop");
    return [
      name,
      Object.fromEntries(
        names.map((role) => [role, hex(over(palette.light[role], bottom))]),
      ),
    ];
  }),
);
const correctionLayers = Object.fromEntries(
  Object.entries(backdrops).map(([name, value]) => {
    const bottom = parse(value);
    if (!bottom || bottom.mode !== "rgb")
      throw new Error("Invalid medium backdrop");
    return [
      name,
      Object.fromEntries(
        (["insert", "delete"] as const).map((kind) => {
          const background = over(
            palette.light[`correction-${kind}-bg`],
            bottom,
          );
          return [
            kind,
            {
              background: hex(background),
              line: hex(
                over(palette.light[`correction-${kind}-line`], background),
              ),
            },
          ];
        }),
      ),
    ];
  }),
);
const banner =
  "SPDX-License-Identifier: AGPL-3.0-or-later OR MIT\nGenerated by scripts/generate.ts. Do not edit; run pnpm tokens:generate.";
const declarations = (entries: Record<string, string>) =>
  Object.entries(entries)
    .map(([key, value]) => `  --st-${key}: ${value};`)
    .join("\n");
const modeBlock = (mode: "light" | "dark") => {
  const entries: Record<string, string> = {};
  for (const name of names) {
    if (name in roles[mode]) {
      const [primitive, alpha = 1] = roles[mode][
        name as keyof typeof roles.light
      ] as RoleValue;
      entries[name] =
        alpha === 1
          ? `var(--st-prim-${primitive})`
          : `oklch(from var(--st-prim-${primitive}) l c h / ${alpha})`;
    } else entries[name] = css(palette[mode][name]);
  }
  return `  color-scheme: ${mode};\n${declarations({ ...entries, ...shadows[mode] })}`;
};
const aliases: Record<string, string> = Object.fromEntries(
  names.map((name) => [`color-${name}`, `var(--st-${name})`]),
);
for (const name of Object.keys(values)) {
  if (
    /^(font-(sans|mono)$|text-|radius-|ease-)/.test(name) ||
    name === "spacing" ||
    name === "tracking-caps"
  )
    aliases[name] = `var(--st-${name})`;
}
for (const name of Object.keys(shadows.light))
  aliases[name === "highlight-inset" ? "shadow-highlight-inset" : name] =
    `var(--st-${name})`;
const resets = ["color", "font", "text", "radius", "shadow", "ease"]
  .map((n) => `  --${n}-*: initial;`)
  .join("\n");
let theme = `/* ${banner} */\n:root {\n${declarations(Object.fromEntries(Object.entries(primitives).map(([name, tuple]) => [`prim-${name}`, css(color(tuple))])))}\n${declarations(values)}\n${modeBlock("light")}\n}\n\n@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n${modeBlock("dark")}\n  }\n}\n:root[data-theme="dark"] {\n${modeBlock("dark")}\n}\n\n@theme inline {\n${resets}\n${Object.entries(
  aliases,
)
  .map(([name, value]) => `  --${name}: ${value};`)
  .join("\n")}\n}\n`;
const durations = Object.fromEntries(
  Object.keys(values)
    .filter((name) => name.startsWith("duration-") || name === "stagger")
    .map((name) => [name, "0ms"]),
);
theme += `\n@media (prefers-reduced-motion: reduce) {\n  :root {\n${declarations(durations)}\n  }\n}\n`;
const exports = { colors, backdrops, opaque, correctionLayers, values };
function literalType(value: unknown): string {
  if (value !== null && typeof value === "object")
    return `{ ${Object.entries(value)
      .map(
        ([key, child]) =>
          `readonly ${JSON.stringify(key)}: ${literalType(child)};`,
      )
      .join(" ")} }`;
  return JSON.stringify(value);
}
const javascript =
  `// ${banner.replaceAll("\n", "\n// ")}\n` +
  Object.entries(exports)
    .map(
      ([name, value]) =>
        `export const ${name} = ${JSON.stringify(value, null, 2)};`,
    )
    .join("\n");
const types =
  `// ${banner.replaceAll("\n", "\n// ")}\n` +
  Object.entries(exports)
    .map(
      ([name, value]) => `export declare const ${name}: ${literalType(value)};`,
    )
    .join("\n") +
  "\nexport type Mode = keyof typeof colors;\nexport type Role = keyof typeof colors.light;\nexport type Backdrop = keyof typeof backdrops;\n";
const outputs = {
  "theme.css": await format(theme, { parser: "css" }),
  "dist/index.js": await format(javascript, { parser: "babel" }),
  "dist/index.d.ts": await format(types, { parser: "typescript" }),
};
for (const [name, content] of Object.entries(outputs)) {
  const path = fileURLToPath(new URL(`../${name}`, import.meta.url));
  if (process.argv.includes("--check")) {
    const existing = await readFile(path, "utf8").catch(() => "");
    if (existing !== content)
      throw new Error(
        `Generated token drift: ${name}; run pnpm tokens:generate`,
      );
  } else await writeFile(path, content);
}
console.log(
  `${pairs.length} gated pairs, zero failures; sRGB and ${process.argv.includes("--check") ? "committed outputs verified" : "outputs generated"}.`,
);

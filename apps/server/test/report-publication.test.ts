const database = testDatabase();
const db = createPrisma(database.appUrl);
let stop: () => Promise<void>;
let api: string;
let features = ["verification-report"];
let publication: { arrived(): void; wait: Promise<void> } | undefined;
function holdPublication() {
  let hit!: () => void, release!: () => void;
  const arrived = new Promise<void>((r) => {
    hit = r;
  });
  publication = {
    arrived: hit,
    wait: new Promise<void>((r) => {
      release = r;
    }),
  };
  return {
    arrived,
    release: () => {
      publication = undefined;
      release();
    },
  };
}
beforeAll(async () => {
  const fixtures = await startDoiFixtures();
  await setupDatabase(database.adminUrl, database.appUrl);
  const boss = await createQueue(database.appUrl);
  const events = await listenForEvents(database.appUrl);
  const quotaValue = () => ({
    consumed: 0,
    remaining: 100,
    granted: 100,
    reserved: 0,
    warning: "none" as const,
    grants: [],
    features,
  });
  const quota = {
    snapshot: () => Promise.resolve(quotaValue()),
    reserve: () =>
      Promise.resolve({ free: [], reserved: 1, quota: quotaValue() }),
    release: async () => {},
    settle: async () => {},
  };
  const runtime = await startWorkerRuntime(
    loadConfig({
      NODE_ENV: "test",
      SOURCE_TASTER_MODE: "standalone",
      DATABASE_URL: database.appUrl,
      SOURCE_TASTER_PLACEHOLDER_DELAY_MS: "0",
      ...fixtures.env,
    }),
    db,
    boss,
    {
      quota,
      authority: {
        async run(_subject, boundary, operation) {
          if (boundary === "commit" && publication) {
            const held = publication;
            held.arrived();
            await held.wait;
          }
          return operation();
        },
      },
    },
  );
  const app = createApp({
    structuring: createParser(),
    heartbeatMs: 100,
    referenceLimit: 1000,
    checks: createCheckStore(db, boss),
    events,
    entitlements: { resolve: () => Promise.resolve(LOCAL_OWNER), quota },
  });
  const server = serve({
    fetch: app.fetch,
    hostname: "127.0.0.1",
    port: await freePort(),
  });
  await once(server, "listening");
  api = `http://127.0.0.1:${(server.address() as { port: number }).port}`;
  stop = async () => {
    runtime.stop();
    await new Promise<void>((r) => server.close(() => r()));
    await events.close();
    await boss.stop();
    await db.$disconnect();
    await fixtures.stop();
    const admin = new pg.Client({ connectionString: database.adminUrl });
    await admin.connect();
    const owned = new URL(database.appUrl);
    await admin.query(
      `DROP DATABASE ${admin.escapeIdentifier(owned.pathname.slice(1))} WITH (FORCE)`,
    );
    await admin.query(`DROP ROLE ${admin.escapeIdentifier(owned.username)}`);
    await admin.end();
  };
});
afterAll(async () => {
  await stop?.();
});
const call = (path: string, body?: object) =>
  fetch(api + path, {
    ...(body ? { method: "POST", body: JSON.stringify(body) } : {}),
    headers: { "content-type": "application/json" },
  });
it("discards generated bytes when the external report entitlement is lost before publication", async () => {
  const created = await call("/v2/checks", {
    references: [
      { originalText: "Original input", fields: { DOI: "10.1038/nphys1170" } },
    ],
  });
  expect(created.status).toBe(201);
  const check = CheckResponse.parse(await created.json()).data;
  await expect
    .poll(
      async () =>
        CheckResponse.parse(await (await call(`/v2/checks/${check.id}`)).json())
          .data.state,
    )
    .toBe("ended");
  const held = holdPublication();
  try {
    const path = `/v2/checks/${check.id}/reports`;
    const requested = await call(path, { language: "en", style: "apa" });
    expect(requested.status).toBe(202);
    const job = ReportResponse.parse(await requested.json()).data;
    await held.arrived;
    features = [];
    held.release();
    await expect
      .poll(async () => (await call(`${path}/${job.id}`)).status)
      .toBe(404);
    features = ["verification-report"];
    expect((await call(`${path}/${job.id}/file`)).status).toBe(404);
    expect((await call(`/v2/checks/${check.id}`)).status).toBe(200);
  } finally {
    features = ["verification-report"];
    held.release();
  }
});
